def main():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    counts = Counter()
    with OUTPUT.open('w', encoding='utf-8', newline='\n') as stream:
        number = 0
        for category, examples in EXAMPLES.items():
            if len(examples) != 12:
                raise ValueError(f'{category} must contain exactly 12 examples')
            for question, answer in examples:
                number += 1
                text = f'<|user|>\n{question}\n<|assistant|>\n{answer}\n'
                row = {
                    'id': f'ja-chat-{number:03d}', 'category': category,
                    'question': question, 'answer': answer, 'text': text,
                }
                stream.write(json.dumps(row, ensure_ascii=False) + '\n')
                counts[category] += 1
    print(json.dumps({'count': number, 'categories': counts, 'path': str(OUTPUT)}, ensure_ascii=False))


if __name__ == '__main__':
    main()
